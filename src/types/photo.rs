//! `FileLocation` — the synthesized download-location union. Schema-shaped
//! photo types (`Photo`, `PhotoSize`, `Document`, `WebDocument`, `GeoPoint`)
//! live in `photo_gen.rs`.

use super::photo_gen::{Document, PhotoSize};

/// Download locations assembled from document/photo fields (client-side
/// synthesis — not a TL union on the wire).
#[derive(Debug, Clone)]
pub enum FileLocation {
    VolumeId {
        volume_id: i64,
        local_id: i32,
        secret: i64,
        reference: Vec<u8>,
        dc_id: i32,
    },
    /// `inputDocumentFileLocation#bad07584` — documents/files. Empty
    /// `thumb_size` downloads the full file; "m" fetches a thumbnail.
    Document {
        id: i64,
        access_hash: i64,
        reference: Vec<u8>,
        thumb_size: String,
        dc_id: i32,
    },
    /// Photo download location, synthesized from a `photo#fb197a65`
    /// (`inputFileLocation#dfdaabe1` on the wire): `thumb_size` selects
    /// the size variant, `size` is the expected byte length.
    Photo {
        id: i64,
        access_hash: i64,
        reference: Vec<u8>,
        thumb_size: String,
        size: i64,
        dc_id: i32,
    },
    Web {
        dc_id: i32,
        url: String,
        size: i32,
    },
    EmojiStickerSet {
        version: i32,
        set_id: i64,
    },
    Unknown,
}

impl Document {
    /// Telegram's stripped thumbnail of this document as displayable
    /// JPEG bytes — `None` when the document carries no stripped size.
    #[must_use]
    pub fn stripped_thumb_jpeg(&self) -> Option<Vec<u8>> {
        if let Self::Document {
            thumbs: Some(thumbs),
            ..
        } = self
        {
            for thumb in thumbs {
                if let PhotoSize::PhotoStrippedSize { bytes, .. } = thumb {
                    let jpeg = stripped_thumb_jpeg(bytes);
                    if !jpeg.is_empty() {
                        return Some(jpeg);
                    }
                }
            }
        }
        None
    }
}

