#[cfg(test)]
mod tests {
    // Test code: empty-slice probes and fixed-offset indexing against
    // hand-built fixtures cannot panic here.
    #![allow(clippy::indexing_slicing, clippy::assert_is_empty)]
    use super::*;

    #[test]
    fn stripped_thumb_needs_magic_and_min_len() {
        assert!(stripped_thumb_jpeg(&[]).is_empty());
        assert!(stripped_thumb_jpeg(&[0x01, 0x02]).is_empty());
        assert!(stripped_thumb_jpeg(&[0x00, 0x01, 0x02, 0x03]).is_empty());
    }

    #[test]
    fn stripped_thumb_round_trips_dimensions() {
        // magic 0x01, height 0x20, width 0x40, one scan byte
        let out = stripped_thumb_jpeg(&[0x01, 0x20, 0x40, 0xaa]);
        assert_eq!(out.len(), 623 + 1 + 2);
        assert_eq!(&out[..2], &[0xff, 0xd8]); // SOI
        assert_eq!(out[164], 0x20); // height byte patched
        assert_eq!(out[166], 0x40); // width byte patched
        assert_eq!(out[623], 0xaa); // scan data
        assert_eq!(&out[out.len() - 2..], &[0xff, 0xd9]); // EOI
    }
}
